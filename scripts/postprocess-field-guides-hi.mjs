function postprocess(obj) {
  if (Array.isArray(obj)) return obj.map(postprocess);
  if (obj && typeof obj === "object") {
    const out = {};
    for (const [k, v] of Object.entries(obj)) {
      if (["technical", "dose_per_acre", "irac_group", "frac_group", "hrac_group", "references", "N_kg_per_acre", "P2O5_kg_per_acre", "K2O_kg_per_acre", "day"].includes(k)) {
        out[k] = v;
      } else {
        out[k] = postprocess(v);
      }
    }
    return out;
  }
  if (typeof obj === "string") {
    let s = obj;
    for (const [re, rep] of REPLACEMENTS) s = s.replace(re, rep);
    return s;
  }
  return obj;
}

