export type FarmerUiKey = keyof (typeof STRINGS)["en"];

export function t(locale: AppLocale | string, key: FarmerUiKey): string {
  const loc = normalizeAppLocale(locale);
  return STRINGS[loc][key] ?? STRINGS.en[key];
}

export function tf(
  locale: AppLocale | string,
  key: FarmerUiKey,
  vars: Record<string, string | number>
): string {
  let out = t(locale, key);
  for (const [name, value] of Object.entries(vars)) {
    out = out.replaceAll(`{${name}}`, String(value));
  }
  return out;
}
