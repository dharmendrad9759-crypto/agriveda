/** Pull leading number and unit from "55 किग्रा (...)" or "500 ग्राम (...)" or "250 मि.ली (...)" */
export function fertilizerAmountParts(amount: string): {
  num: string;
  unit: string;
  rest: string;
} {
  const m = amount.match(
    /^([\d.]+)\s*(किग्रा|kg|ग्राम|g|मि\.?ली|ml|लीटर|L|टन)?\s*(.*)$/i
  );
  if (!m) return { num: amount, unit: "किग्रा", rest: "" };
  const rawUnit = (m[2] || "किग्रा").toLowerCase();
  const unit =
    rawUnit === "kg" || rawUnit === "किग्रा"
      ? "किग्रा"
      : rawUnit === "g" || rawUnit === "ग्राम"
        ? "ग्राम"
        : rawUnit === "ml" || rawUnit.startsWith("मि")
          ? "मि.ली"
          : rawUnit === "l" || rawUnit === "लीटर"
            ? "लीटर"
            : rawUnit === "टन"
              ? "टन"
              : "किग्रा";
  const note = (m[3] || "").replace(/^[·\-–—]\s*/, "").trim();
  return {
    num: m[1],
    unit,
    rest: note,
  };
}

function formatScaledNum(val: number): string {
  const rounded = Math.round(val * 100) / 100;
  return Number.isInteger(rounded) ? String(rounded) : String(Math.round(rounded * 10) / 10);
}

/**
 * Scale a bag/product amount string by `acres` (Dose × N).
 * Handles kg/किग्रा, g/ग्राम, ml/मि.ली, while preserving grade ratios (19:19:19) and per-litre/per-plant notes.
 */
export function scaleBagKg(kgStr: string, acres: number): string {
  if (!Number.isFinite(acres) || acres <= 0 || acres === 1) return kgStr;

  // Scale leading number + unit
  return kgStr.replace(
    /^([\d.]+)(\s*)(किग्रा|kg|ग्राम|g|मि\.?ली|ml|टन)/i,
    (_, numStr: string, space: string, unit: string) => {
      const base = parseFloat(numStr);
      if (!Number.isFinite(base)) return _;
      const scaled = base * acres;
      const uLower = unit.toLowerCase();
      if ((uLower === "ग्राम" || uLower === "g") && scaled >= 1000) {
        return `${formatScaledNum(scaled / 1000)} किग्रा`;
      }
      if ((uLower === "मि.ली" || uLower === "मिली" || uLower === "ml") && scaled >= 1000) {
        return `${formatScaledNum(scaled / 1000)} लीटर`;
      }
      const normUnit =
        uLower === "kg"
          ? "किग्रा"
          : uLower === "g"
            ? "ग्राम"
            : uLower === "ml"
              ? "मि.ली"
              : unit;
      return `${formatScaledNum(scaled)}${space}${normUnit}`;
    }
  );
}

/** Standard Indian retail pack size (kg) per product — urea 45, DAP/MOP/SSP 50, zinc 10 … */
export function fertilizerPackKg(name: string): {
  kg: number;
  unitHi: "बोरी" | "थैली" | "पैकेट" | "बोतल";
  isSubKg?: boolean;
} {
  const n = name.toLowerCase();
  if (n.includes("urea") || n.includes("यूरिया")) return { kg: 45, unitHi: "बोरी" };
  if (
    n.includes("19:19:19") ||
    n.includes("12:61:00") ||
    n.includes("00:52:34") ||
    n.includes("00:00:50") ||
    n.includes("13:00:45") ||
    n.includes("घुलनशील")
  ) {
    return { kg: 1, unitHi: "पैकेट" };
  }
  if (
    n.includes("humic") ||
    n.includes("ह्यूमिक") ||
    n.includes("chelated") ||
    n.includes("चिलेटेड") ||
    n.includes("boron 20") ||
    n.includes("घुलनशील बोरॉन") ||
    n.includes("thiourea") ||
    n.includes("थायोयूरिया") ||
    n.includes("molybdate") ||
    n.includes("मोलिब्डेट") ||
    n.includes("trichoderma") ||
    n.includes("ट्राइकोडर्मा")
  ) {
    return { kg: 1, unitHi: "पैकेट", isSubKg: true };
  }
  if (n.includes("liquid") || n.includes("लिक्विड")) {
    return { kg: 1, unitHi: "बोतल", isSubKg: true };
  }
  if (n.includes("mycorrhiza") || n.includes("माइकोराइजा")) return { kg: 4, unitHi: "पैकेट" };
  if (n.includes("sulphur") || n.includes("सल्फर")) return { kg: 3, unitHi: "पैकेट" };
  if (n.includes("zyme") || n.includes("सागरिका") || n.includes("जाइम")) return { kg: 10, unitHi: "थैली" };
  if (n.includes("zinc") || n.includes("जिंक") || n.includes("znso")) return { kg: 5, unitHi: "थैली" };
  if (n.includes("borax") || n.includes("बोरेक्स")) return { kg: 1, unitHi: "पैकेट" };
  if (n.includes("magnesium") || n.includes("मैग्नीशियम")) return { kg: 25, unitHi: "बोरी" };
  if (n.includes("calcium nitrate") || n.includes("कैल्शियम नाइट्रेट")) return { kg: 25, unitHi: "बोरी" };
  if (n.includes("ferrous") || n.includes("आयरन") || n.includes("फेरस")) return { kg: 5, unitHi: "थैली" };
  if (n.includes("neem") || n.includes("नीम")) return { kg: 50, unitHi: "बोरी" };
  return { kg: 50, unitHi: "बोरी" };
}

/** "75 किग्रा" + Urea → "1 बोरी (45 किग्रा) + 30 किग्रा" — simple farmer wording. */
export function fertilizerPackHi(name: string, kg: number, unit = "किग्रा"): string {
  if (!Number.isFinite(kg) || kg <= 0) return "";
  if (unit === "ग्राम") {
    return `${Math.round(kg)} ग्राम पैक`;
  }
  if (unit === "मि.ली") {
    return `${Math.round(kg)} मि.ली बोतल`;
  }
  if (unit === "लीटर") {
    return `${formatScaledNum(kg)} लीटर बोतल`;
  }
  const { kg: pack, unitHi, isSubKg } = fertilizerPackKg(name);
  if (isSubKg) {
    return `${formatScaledNum(kg)} किग्रा (${unitHi})`;
  }
  if (pack <= 1) return `${Math.ceil(kg)} ${unitHi} (1 किग्रा वाले)`;
  const whole = Math.floor(kg / pack);
  const rem = Math.round((kg - whole * pack) * 10) / 10;
  const packLabel = `${pack} किग्रा वाली`;
  if (whole === 0) {
    if (kg / pack >= 0.45 && kg / pack <= 0.55) return `लगभग आधी ${unitHi} (${packLabel})`;
    return `${unitHi} से कम — ${formatScaledNum(kg)} किग्रा खुला/छोटा पैक लें`;
  }
  if (rem <= 1) return `${whole} ${unitHi} (${packLabel})`;
  if (pack - rem <= 1) return `${whole + 1} ${unitHi} (${packLabel})`;
  return `${whole} ${unitHi} + ${formatScaledNum(rem)} किग्रा (${packLabel})`;
}
