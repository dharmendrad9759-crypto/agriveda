export function formatNutrientValue(v: NutrientValue): string {
  if (typeof v === "string" || typeof v === "number") return String(v);
  return Object.entries(v)
    .map(([k, val]) => {
      const label =
        k === "total"
          ? "कुल"
          : k === "basal"
            ? "बुवाई"
            : k === "split"
              ? "भाग"
              : k === "source"
                ? "स्रोत"
                : k === "note"
                  ? "नोट"
                  : k === "dose"
                    ? "खुराक"
                    : k === "apply"
                      ? "कब"
                      : k === "symptoms"
                        ? "लक्षण"
                        : k === "essential"
                          ? "ज़रूरी"
                          : k === "top1"
                            ? "पहली किस्त"
                            : k === "top2"
                              ? "दूसरी किस्त"
                              : k === "top3"
                                ? "तीसरी किस्त"
                                : k;
      return `${label}: ${val}`;
    })
    .join(" · ");
}

