export function dxForPart(cropId: string, part: PlantPart): PartDx[] {
  return PART_DX.filter((row) => row.cropId === cropId && row.part === part);
}

export function dxPartsForCrop(cropId: string): PlantPart[] {
  const seen: PlantPart[] = [];
  for (const row of PART_DX) {
    if (row.cropId === cropId && !seen.includes(row.part)) seen.push(row.part);
  }
  return seen;
}
