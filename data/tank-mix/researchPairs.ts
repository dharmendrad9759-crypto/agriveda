export function researchPairKey(a: string, b: string): string {
  const x = a.toLowerCase().trim();
  const y = b.toLowerCase().trim();
  return x < y ? `${x}||${y}` : `${y}||${x}`;
}

export function getResearchPairMap(): Record<string, ResearchPair> {
  const map: Record<string, ResearchPair> = {};
  const aliases: Record<string, string> = {
    "elemental sulphur": "sulfur",
    sulphur: "sulfur",
    "2,4-d": "24-d",
    "profenophos": "profenofos",
  };
  const canon = (s: string) => {
    const n = s.toLowerCase().trim();
    return aliases[n] || n;
  };
  for (const p of researchPairs) {
    map[researchPairKey(canon(p.a), canon(p.b))] = p;
  }
  return map;
}
